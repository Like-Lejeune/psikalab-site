export type UIKey = keyof (typeof ui)['fr'];

export function useT(lang: Lang) {
  return (key: UIKey, vars: Record<string, string> = {}) => {
    let s: string = ui[lang][key] ?? ui[defaultLang][key];
    for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, v);
    return s;
  };
}

/** Chemin d'une page dans une langue : path('en', 'events') -> /en/events/ */
export function path(lang: Lang, page = '') {
  return `/${lang}/${page ? page.replace(/^\/|\/$/g, '') + '/' : ''}`;
}

export function otherLang(lang: Lang): Lang {
  return lang === 'fr' ? 'en' : 'fr';
}

export function getStaticLangPaths() {
  return langs.map((lang) => ({ params: { lang } }));
}
